# -*- coding: utf-8 -*-
"""FEI · HEL — build i18n-data.js from the translation sources.

    python3 tools/build_i18n.py           # write i18n-data.js
    python3 tools/build_i18n.py --check   # also report Korean strings without a translation
"""
import html as html_lib
import json
import os
import re
import sys
from html.parser import HTMLParser

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import i18n_1  # noqa: E402
import i18n_2  # noqa: E402
import i18n_3  # noqa: E402
import i18n_4  # noqa: E402

LANGS = ("en", "ja", "zh")
ATTRS = ("aria-label", "alt", "placeholder", "title", "content")


def norm(value):
    return re.sub(r"[\s\u00a0\u200b]+", " ", value).strip()


class Collector(HTMLParser):
    """Collects Korean text nodes and attribute values outside translated blocks."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack = []          # list of (tag, skip)
        self.texts = []
        self.attrs = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        skip = any(s for _, s in self.stack)
        # <html lang="ko"> states the document language; it is not a block that
        # must be skipped, and treating it as one made the coverage check vacuous.
        skip = skip or "data-i18n-html" in attrs or ("lang" in attrs and tag != "html")
        for name, value in attrs.items():
            if name in ATTRS and value and re.search(r"[가-힣]", value):
                self.attrs.append(value)
        if tag in ("br", "img", "input", "meta", "link", "hr"):
            return
        self.stack.append((tag, skip))

    def handle_startendtag(self, tag, attrs):
        attrs = dict(attrs)
        for name, value in attrs.items():
            if name in ATTRS and value and re.search(r"[가-힣]", value):
                self.attrs.append(value)

    def handle_endtag(self, tag):
        while self.stack:
            if self.stack.pop()[0] == tag:
                break

    def handle_data(self, data):
        if re.search(r"[가-힣]", data) and not any(s for _, s in self.stack):
            self.texts.append(data)


def main():
    text = {}
    duplicates = []
    entries = []
    for module in (i18n_1, i18n_2, i18n_3, i18n_4):
        entries.extend(getattr(module, "ENTRIES", []))
    entries.extend(getattr(i18n_4, "CAPTIONS", []))
    entries.extend(getattr(i18n_4, "EXTRA", []))

    for ko, en, ja, zh in entries:
        key = norm(ko)
        value = {"en": en, "ja": ja, "zh": zh}
        if key in text and text[key] != value:
            duplicates.append(key)
        text[key] = value

    data = {
        "text": text,
        "html": getattr(i18n_4, "BLOCKS", {}),
        "patterns": getattr(i18n_4, "PATTERNS", []),
    }

    if duplicates:
        print("duplicate keys with different values:")
        for key in duplicates:
            print("  -", key)

    body = json.dumps(data, ensure_ascii=False, indent=2)
    out = (
        "/* FEI · HEL — translation table (generated by tools/build_i18n.py)\n"
        "   Do not edit by hand: edit tools/i18n_1..4.py and rebuild. */\n"
        "window.FEI_I18N_DATA = " + body + ";\n"
    )
    with open(os.path.join(ROOT, "i18n-data.js"), "w", encoding="utf-8") as fh:
        fh.write(out)

    print("i18n-data.js written: %d strings, %d html blocks, %d patterns"
          % (len(text), len(data["html"]), len(data["patterns"])))

    if "--check" in sys.argv:
        check(text)


def covered(key, text):
    if key in text:
        return True
    for rule in getattr(i18n_4, "PATTERNS", []):
        if re.match(rule["re"], key):
            return True
    return False


def check(text):
    source = open(os.path.join(ROOT, "index.html"), encoding="utf-8").read()
    source = re.sub(r"<script.*?</script>", "", source, flags=re.S)
    source = re.sub(r"<style.*?</style>", "", source, flags=re.S)

    collector = Collector()
    collector.feed(source)

    missing = {}
    for chunk in collector.texts:
        key = norm(html_lib.unescape(chunk))
        if not covered(key, text):
            missing[key] = missing.get(key, 0) + 1
    for value in collector.attrs:
        key = norm(html_lib.unescape(value))
        if not covered(key, text):
            missing[key] = missing.get(key, 0) + 1

    print("\nno translation (%d distinct):" % len(missing))
    for key in missing:
        print("  -", key)


if __name__ == "__main__":
    main()
